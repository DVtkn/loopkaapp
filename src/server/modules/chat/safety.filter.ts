export interface SafetyCheckResult {
  hasRisk: boolean;
  systemNotice?: string;
}

const EMERGENCY_PATTERNS = [
  /суицид|покончить с собой|не хочу жить|убить себя|спрыгнуть/i,
  /бьет меня|ударил|душит|угрожает расправой|боюсь за свою жизнь|домашнее насилие/i,
  /самоповрежден|режу вены|причинить себе вред|наглотаться таблеток/i,
];

export function evaluateSafetyRisk(text: string): SafetyCheckResult {
  const isTriggered = EMERGENCY_PATTERNS.some((pattern) => pattern.test(text || ""));

  if (!isTriggered) {
    return { hasRisk: false };
  }

  return {
    hasRisk: true,
    systemNotice:
      "Я чувствую, как вам тяжело и небезопасно прямо сейчас. " +
      "Как алгоритм, я не имею права и квалификации оказывать экстренную кризисную помощь. " +
      "Пожалуйста, свяжитесь со специалистами, которые могут помочь немедленно:\n\n" +
      "• Единый телефон доверия: 8-800-2000-122 (бесплатно, анонимно, круглосуточно)\n" +
      "• Кризисный центр помощи: 8-800-7000-600\n" +
      "• Неотложная психологическая помощь: 051 (с городского) или +7 (495) 051\n\n" +
      "Сделайте этот шаг ради вашей безопасности. Вы не одни.",
  };
}
